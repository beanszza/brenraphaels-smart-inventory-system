import { Supplier } from "./types";

export interface SuppliersPdfOptions {
  statusFilter?: string;
  searchQuery?: string;
  staffName?: string;
}

export async function downloadSuppliersPdf(suppliers: Supplier[], options: SuppliersPdfOptions = {}) {
  try {
    const jspdfModule = await import("jspdf");
    const jsPDF = jspdfModule.jsPDF || (jspdfModule as any).default;
    const autoTableModule = await import("jspdf-autotable");
    const autoTable = (autoTableModule as any).default || autoTableModule;

    const doc = new jsPDF({ format: "a4", orientation: "portrait" });

    const reportDate = new Date().toLocaleDateString("en-US", {
      month: "2-digit",
      day: "2-digit",
      year: "numeric",
    });

    const reportTime = new Date().toLocaleTimeString("en-US", {
      hour: "numeric",
      minute: "2-digit",
      hour12: true,
    });

    // 1. Company Header (Matches Official Bren Raphael's Document Template)
    doc.setFont("helvetica", "bold");
    doc.setFontSize(14);
    doc.setTextColor(20, 20, 20);
    doc.text("BREN RAPHAEL'S UBE JAM & HALAYA", 14, 20);

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(80, 80, 80);
    doc.text("Block 14 Lot1A, Marigman St., San Roque,", 14, 25);
    doc.text("Antipolo, 1870 Rizal", 14, 29);
    doc.text("Contact: (02) 8650-1234 | info@brenraphaels.com", 14, 33);

    // Document Title & Reference (Top Right)
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(100, 100, 100);
    doc.text("SUPPLIER DIRECTORY REPORT", 196, 20, { align: "right" });

    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.setTextColor(20, 20, 20);
    doc.text("OFFICIAL VENDOR DIRECTORY", 196, 26, { align: "right" });

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(60, 60, 60);
    doc.text(
      options.statusFilter && options.statusFilter !== "All"
        ? `STATUS: ${options.statusFilter.toUpperCase()} ONLY`
        : "STATUS: COMPLETE DIRECTORY",
      196,
      32,
      { align: "right" }
    );

    // Top Divider Line
    doc.setDrawColor(30, 30, 30);
    doc.setLineWidth(0.6);
    doc.line(14, 38, 196, 38);

    // 2. Report Details (Left & Right Columns)
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(100, 100, 100);
    doc.text("DIRECTORY INFORMATION:", 14, 45);

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.setTextColor(20, 20, 20);
    doc.text("PARTNER & VENDOR REGISTRY", 14, 50);

    const activeCount = suppliers.filter((s) => s.isActive).length;
    const inactiveCount = suppliers.filter((s) => !s.isActive).length;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(60, 60, 60);
    doc.text(`Status Scope: ${options.statusFilter || "All"} (Active: ${activeCount}, Inactive: ${inactiveCount})`, 14, 55.5);
    if (options.searchQuery?.trim()) {
      doc.text(`Search Keyword: "${options.searchQuery.trim().slice(0, 35)}"`, 14, 60);
    }

    // Right Column
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(100, 100, 100);
    doc.text("DOCUMENT REFERENCE:", 196, 45, { align: "right" });

    doc.setFont("helvetica", "bold");
    doc.setFontSize(9.5);
    doc.setTextColor(20, 20, 20);
    doc.text(`Total Records: ${suppliers.length}`, 196, 50, { align: "right" });

    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(60, 60, 60);
    doc.text(`Generated: ${reportDate} ${reportTime}`, 196, 55.5, { align: "right" });
    doc.text(`Generated By: ${options.staffName || "Authorized Administrator"}`, 196, 60, { align: "right" });

    const infoBottomY = options.searchQuery?.trim() ? 66 : 64;

    // Section Divider Line
    doc.setDrawColor(30, 30, 30);
    doc.setLineWidth(0.6);
    doc.line(14, infoBottomY, 196, infoBottomY);

    // 3. Suppliers Table
    const tableData: string[][] = suppliers.map((supplier, index) => {
      const code = supplier.supplierCode || `SUP-${String(supplier.supplierId).padStart(3, "0")}`;
      const contactInfo = [supplier.phone, supplier.email].filter(Boolean).join("\n");
      const statusText = supplier.isActive ? "Active" : "Inactive";
      return [
        String(index + 1),
        code,
        supplier.companyName || "—",
        supplier.contactPerson || "—",
        contactInfo || "—",
        supplier.address || "—",
        statusText,
      ];
    });

    autoTable(doc, {
      startY: infoBottomY + 4,
      head: [
        [
          "#",
          "SUPPLIER CODE",
          "COMPANY NAME",
          "CONTACT PERSON",
          "CONTACT INFO",
          "ADDRESS",
          "STATUS",
        ],
      ],
      body: tableData.length > 0 ? tableData : [["—", "—", "No suppliers found", "—", "—", "—", "—"]],
      theme: "plain",
      styles: {
        fontSize: 7.5,
        cellPadding: 3,
        textColor: [30, 30, 30],
        lineColor: [220, 220, 220],
        lineWidth: 0.2,
        overflow: "linebreak",
      },
      headStyles: {
        textColor: [10, 10, 10],
        fontStyle: "bold",
        fontSize: 7.5,
        lineColor: [30, 30, 30],
        lineWidth: 0.6,
      },
      columnStyles: {
        0: { cellWidth: 8, halign: "center" },
        1: { cellWidth: 24, halign: "left", fontStyle: "bold" },
        2: { cellWidth: 42, halign: "left", fontStyle: "bold" },
        3: { cellWidth: 28, halign: "left" },
        4: { cellWidth: 38, halign: "left" },
        5: { cellWidth: 28, halign: "left" },
        6: { cellWidth: 14, halign: "center" },
      },
    });

    let currentY = (doc as any).lastAutoTable?.finalY ? (doc as any).lastAutoTable.finalY + 4 : infoBottomY + 30;

    // 4. Total Count Summary
    doc.setDrawColor(30, 30, 30);
    doc.setLineWidth(0.6);
    doc.line(14, currentY, 196, currentY);

    currentY += 6;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(20, 20, 20);
    doc.text("TOTAL SUPPLIERS LISTED", 14, currentY);

    doc.setFontSize(9.5);
    doc.text(`${suppliers.length} supplier(s) (Active: ${activeCount}, Inactive: ${inactiveCount})`, 196, currentY, {
      align: "right",
    });

    currentY += 4;
    doc.line(14, currentY, 196, currentY);

    // 5. Signatures Section
    if (currentY + 36 > 275) {
      doc.addPage();
      currentY = 25;
    } else {
      currentY += 12;
    }

    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(80, 80, 80);
    doc.text("PREPARED BY:", 14, currentY);
    doc.text("REVIEWED & VERIFIED BY:", 110, currentY);

    currentY += 14;
    doc.setDrawColor(180, 180, 180);
    doc.setLineWidth(0.4);
    doc.line(14, currentY, 85, currentY);
    doc.line(110, currentY, 196, currentY);

    currentY += 4;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(40, 40, 40);
    doc.text(options.staffName || "Authorized Administrator", 14, currentY);
    doc.text("Operations / IMS Head", 110, currentY);

    currentY += 4;
    doc.setFontSize(7.5);
    doc.setTextColor(110, 110, 110);
    doc.text(`Date: ${reportDate}`, 14, currentY);
    doc.text("Date: —", 110, currentY);

    // Footer on all pages
    const pageCount = (doc as any).internal.getNumberOfPages();
    for (let i = 1; i <= pageCount; i++) {
      doc.setPage(i);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(7.5);
      doc.setTextColor(130, 130, 130);
      doc.text(
        `Bren Raphael's IMS — Supplier Management Directory Report | Page ${i} of ${pageCount}`,
        14,
        288
      );
    }

    const dateStamp = new Date().toISOString().split("T")[0];
    doc.save(`bren_raphaels_suppliers_directory_${dateStamp}.pdf`);
  } catch (error) {
    console.error("Failed to generate Supplier Directory PDF report:", error);
    throw error;
  }
}
